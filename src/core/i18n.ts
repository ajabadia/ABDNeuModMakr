export const appI18n = createSynthI18n<AppLocale>({
  locales: NEUMODMAKR_LOCALES,
  defaultLocale: 'es',
  storageKey: STORAGE_KEY_LOCALE,
  legacyStorageKeys: LEGACY_STORAGE_KEYS_LOCALE,
  detectBrowserLocale: true,
});

// Initialize locale on module load and sync <html lang="...">
const initialLocale = appI18n.initI18n();
if (typeof document !== 'undefined' && document.documentElement) {
  document.documentElement.lang = initialLocale;
}

appI18n.onLocaleChange((nextLocale) => {
  if (typeof document !== 'undefined' && document.documentElement) {
    document.documentElement.lang = nextLocale;
  }
  if (typeof window !== 'undefined' && typeof CustomEvent !== 'undefined') {
    window.dispatchEvent(new CustomEvent('abd:locale-change', { detail: { locale: nextLocale } }));
  }
});

export function getAppLocale(): AppLocale {
  return appI18n.getLocale();
}

export function isEs(): boolean {
  return getAppLocale() === 'es';
}

export function setAppLocale(locale: AppLocale): void {
  appI18n.setLocale(locale);
}

export function onAppLocaleChange(cb: (locale: AppLocale) => void): () => void {
  return appI18n.onLocaleChange(cb);
}

export function tApp(path: string, params?: Record<string, string | number>): string {
  return appI18n.t(path, params);
}
